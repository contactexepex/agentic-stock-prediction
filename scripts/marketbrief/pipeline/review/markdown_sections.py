"""Report sections of the weekly review: header, ranges, direction calls and proper scores."""

from __future__ import annotations

from marketbrief.analytics import scoring
from marketbrief.constants.review import EARNINGS_TAG
from marketbrief.core.horizons import horizons
from marketbrief.constants.scoring import BASIS_NOTE
from marketbrief.pipeline.review.markdown_cells import flag, fnum, fpct, range_row
from marketbrief.utils.markdown import markdown_table


def window_names(rec: dict, review_config: dict) -> dict:
    """Display names of the review windows."""
    win_names = {
        "week": f"week {rec['week']}",
        "rolling": f"last {review_config['rolling_days']} days",
        "all": "since start",
    }
    return win_names


def header_lines(cfg, rec, review_config, review_data) -> list[str]:
    """Title, disclaimer, sample sizes and the low-sample and partial-week notes."""
    lines = [
        f"# Weekly review: {cfg['name']}, {rec['week']} ({rec['week_start']} to {rec['week_end']})",
        "",
        "_Research log, not investment advice. Generated by `scripts/review.py`. Proposed changes are never "
        "applied automatically: a human decides and edits `config/ranges.yaml` by hand._",
        "",
        f"Scored ranges: week **{rec['n_ranges_week']}** · last {review_config['rolling_days']} days "
        f"**{rec['n_ranges_30d']}** · "
        f"since start **{rec['n_ranges_all']}**. Scored calls: week **{rec['n_calls_week']}** · since start "
        f"**{rec['n_calls_all']}**. Windows count ranges by target date, up to {rec['week_end']}.",
        "",
    ]
    if rec["low_sample"]:
        lines += [
            f"> **Low sample:** fewer than {review_config['min_n_recommend']} live scored ranges since start. Live "
            f"numbers "
            "are indicative only and no proposal is made from them. Rows with fewer than "
            f"{review_config['min_n']} items are flagged `low n`.",
            "",
        ]
    if review_data.get("partial_week"):
        lines += ["> The review week has not ended yet: numbers are partial.", ""]

    return lines


def range_lines(review_config, review_data, win_names) -> list[str]:
    """Ranges: coverage against the 50% and 80% targets, in total and by regime, sector and note."""
    lines = []
    header = [
        "Window",
        "H",
        "n",
        "50% cover",
        "80% cover",
        "Naive 50%",
        "Naive 80%",
        "80% width",
        "Naive width",
        "80% score",
        "Naive score",
        "Flag",
    ]
    rows = [
        range_row([win_names[window], horizon], stats, review_config)
        for window, per in review_data["ranges"].items()
        for horizon, stats in per.items()
    ]
    lines += [
        "## Ranges: coverage vs target",
        "",
        "Targets 50% and 80%. Width and interval score in % of price; score is lower-is-better. Naive = last "
        "close +/- 20-day volatility.",
        "",
        markdown_table(header, rows),
    ]
    for title, key in (("By regime", "regime"), ("By sector", "sector"), ("By widening note", "note")):
        rows = [
            range_row([win_names[window], group_name], stats, review_config)
            for window, per in review_data["breakdowns"].items()
            for group_name, stats in per[key].items()
        ]
        lines += [f"### {title}", "", markdown_table(["Window", "Group · H", *header[2:]], rows)]
    earnings_keys = [f"{EARNINGS_TAG} · {horizon}d" for horizon in horizons()]
    earnings_rows = [
        range_row([win_names[window], key], per["note"][key], review_config)
        for window, per in review_data["breakdowns"].items()
        for key in earnings_keys
        if key in per["note"]
    ]
    lines += [
        "### Earnings-day coverage per horizon",
        "",
        "N+k ranges with an earnings day in the horizon, against the 50% and 80% targets: the evidence for a "
        "per-horizon earnings multiple (`earnings_vol_multiple`; issue #16).",
        "",
        markdown_table(["Window", "Group · H", *header[2:]], earnings_rows),
    ]
    lines += [
        "Notes: `cue` overnight cue, `ai_call` AI direction (drift), `ai_widen` AI widened, `earnings` "
        "earnings in horizon, `event` major market event, `regime` regime widening, `none` no adjustment.",
        "",
    ]

    return lines


def call_lines(review_config, review_data, win_names) -> list[str]:
    """Direction calls against the always-up baseline, and the confidence bands."""
    lines = []
    rows = [
        [
            win_names[window],
            horizon,
            stats["n"],
            fpct(stats.get("hit_rate")),
            fpct(stats.get("always_up")),
            scoring.percent(stats.get("edge"), sign=True),
            fpct(stats.get("mean_confidence")),
            flag(stats["n"], review_config),
        ]
        for window, per in review_data["calls"].items()
        for horizon, stats in per.items()
    ]
    lines += [
        "## Direction calls",
        "",
        "Hit rate vs the always-up baseline on the same tickers and dates. " + BASIS_NOTE
        + " H and Band name the basis.",
        "",
        markdown_table(["Window", "H", "n", "Hit rate", "Always-up", "Edge", "Mean conf.", "Flag"], rows),
        "### By confidence band",
        "",
        markdown_table(
            ["Window", "Band", "n", "Mean conf.", "Hit rate", "Gap", "Flag"],
            [
                [
                    win_names[window],
                    band,
                    stats["n"],
                    fpct(stats.get("mean_confidence")),
                    fpct(stats.get("hit_rate")),
                    scoring.percent(stats.get("gap"), sign=True),
                    flag(stats["n"], review_config),
                ]
                for window, per in review_data["bands"].items()
                for band, stats in per.items()
            ],
        ),
    ]

    return lines


def score_lines(review_config, review_data, win_names) -> list[str]:
    """Proper scores: Brier and log loss of calls, reliability, interval and quantile scores of ranges."""
    lines = []
    sc_rows = [
        [
            win_names[window],
            horizon,
            stats["n"],
            fnum(stats.get("brier")),
            fnum(stats.get("log_loss")),
            fnum(stats.get("brier_skill")),
            flag(stats["n"], review_config),
        ]
        for window, per in review_data["scores"].items()
        for horizon, stats in per["calls"].items()
    ]
    rel_rows = [  # per scoring basis
        [
            basis,
            row["bin"],
            row["n"],
            fpct(row["mean_conf"]),
            fpct(row["hit_rate"]),
            f"{fpct(row['wilson_lo'])} to {fpct(row['wilson_hi'])}" if row["n"] else "–",
        ]
        for basis, rows in review_data["scores"]["all"]["reliability"].items()
        for row in rows
    ]
    rq_rows = [
        [
            win_names[window],
            horizon,
            stats["n"],
            fpct(stats.get("cover50")),
            fpct(stats.get("cover80")),
            fnum(stats.get("is50_pct")),
            fnum(stats.get("is80_pct")),
            fnum(stats.get("qs_pct")),
            flag(stats["n"], review_config),
        ]
        for window, per in review_data["scores"].items()
        for horizon, stats in per["ranges"].items()
    ]
    lines += [
        "## Proper scores",
        "",
        "Calls: Brier score (a coin flip scores 0.250) and log loss (coin flip 0.693), lower is better; skill = "
        "1 - Brier / 0.25 (above 0 beats a coin flip).",
        "",
        markdown_table(["Window", "H", "n", "Brier", "Log loss", "Skill", "Flag"], sc_rows),
        "### Reliability (since start): stated confidence vs hit rate",
        "",
        markdown_table(["Basis", "Confidence", "n", "Mean stated", "Hit rate", "Wilson 95%"], rel_rows),
        "### Ranges: interval and quantile scores",
        "",
        "In % of price, lower is better. Quantile score = mean pinball loss over the four published quantiles "
        "(q10, q25, q75, q90), a coarse CRPS estimate.",
        "",
        markdown_table(
            ["Window", "H", "n", "50% cover", "80% cover", "50% score", "80% score", "Quantile score", "Flag"], rq_rows
        ),
    ]
    return lines
