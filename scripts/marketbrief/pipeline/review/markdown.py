"""The weekly review's markdown report."""
from __future__ import annotations

import math
from marketbrief.analytics import scoring
from marketbrief.core.market_config import load_ranges_config
from marketbrief.utils.markdown import markdown_table


def fpct(v, digits: int = 0) -> str:
    return scoring.percent(v, digits)


def fnum(v, digits: int = 3) -> str:
    return "–" if v is None or (isinstance(v, float) and math.isnan(v)) else f"{v:.{digits}f}"


def fval(v) -> str:
    if isinstance(v, dict):
        return "{" + ", ".join(f"{k}: {x}" for k, x in v.items()) + "}"
    return str(v)


def flag(n: int, rv: dict) -> str:
    return "low n" if n < rv["min_n"] else ""


def range_row(label: list, s: dict, rv: dict) -> list:
    return [*label, s["n"], fpct(s.get("cover50")), fpct(s.get("cover80")), fpct(s.get("naive_cover50")),
            fpct(s.get("naive_cover80")), fnum(s.get("width80_pct"), 2), fnum(s.get("naive_width80_pct"), 2),
            fnum(s.get("score80_pct")), fnum(s.get("naive_score80_pct")), flag(s["n"], rv)]


def ablation_rows(ab: dict) -> list[list]:
    rows = []
    for v in ab.get("variants") or []:
        hs = list(v["by_h"])
        join = lambda key, f: " / ".join(f(v["by_h"][h].get(key)) for h in hs) or "–"  # noqa: E731
        rel = (v.get("vs_current") or {}).get("rel_score")
        rows.append([v["name"], v["n"], join("cover50", fpct), join("cover80", fpct),
                     join("width80_pct", lambda x: fnum(x, 2)), join("score80_pct", fnum),
                     "–" if rel is None else f"{rel:+.1%}", v.get("verdict", "")])
    return rows


def markdown(cfg: dict, rv: dict, rec: dict, d: dict) -> str:
    hz = " / ".join(f"{h}d" for h in load_ranges_config(cfg["market"])["horizons"])
    win_names = {"week": f"week {rec['week']}", "rolling": f"last {rv['rolling_days']} days", "all": "since start"}
    lines = [f"# Weekly review: {cfg['name']}, {rec['week']} ({rec['week_start']} to {rec['week_end']})", "",
             "_Research log, not investment advice. Generated by `scripts/review.py`. Proposed changes are never "
             "applied automatically: a human decides and edits `config/ranges.yaml` by hand._", "",
             f"Scored ranges: week **{rec['n_ranges_week']}** · last {rv['rolling_days']} days **{rec['n_ranges_30d']}** · "
             f"since start **{rec['n_ranges_all']}**. Scored calls: week **{rec['n_calls_week']}** · since start "
             f"**{rec['n_calls_all']}**. Windows count ranges by target date, up to {rec['week_end']}.", ""]
    if rec["low_sample"]:
        lines += [f"> **Low sample:** fewer than {rv['min_n_recommend']} live scored ranges since start. Live numbers "
                  "are indicative only and no proposal is made from them. Rows with fewer than "
                  f"{rv['min_n']} items are flagged `low n`.", ""]
    if d.get("partial_week"):
        lines += ["> The review week has not ended yet: numbers are partial.", ""]

    hdr = ["Window", "H", "n", "50% cover", "80% cover", "Naive 50%", "Naive 80%", "80% width", "Naive width",
           "80% score", "Naive score", "Flag"]
    rows = [range_row([win_names[w], h], s, rv) for w, per in d["ranges"].items() for h, s in per.items()]
    lines += ["## Ranges: coverage vs target", "",
              "Targets 50% and 80%. Width and interval score in % of price; score is lower-is-better. Naive = last "
              "close +/- 20-day volatility.", "", markdown_table(hdr, rows)]
    for title, key in (("By regime", "regime"), ("By sector", "sector"), ("By widening note", "note")):
        rows = [range_row([win_names[w], k], s, rv) for w, per in d["breakdowns"].items() for k, s in per[key].items()]
        lines += [f"### {title}", "", markdown_table(["Window", "Group · H", *hdr[2:]], rows)]
    lines += ["Notes: `cue` overnight cue, `ai_call` AI direction (drift), `ai_widen` AI widened, `earnings` "
              "earnings in horizon, `event` major market event, `regime` regime widening, `none` no adjustment.", ""]

    rows = [[win_names[w], h, s["n"], fpct(s.get("hit_rate")), fpct(s.get("always_up")),
             scoring.percent(s.get("edge"), sign=True), fpct(s.get("mean_confidence")), flag(s["n"], rv)]
            for w, per in d["calls"].items() for h, s in per.items()]
    lines += ["## Direction calls", "", "Hit rate vs the always-up baseline on the same tickers and dates.", "",
              markdown_table(["Window", "H", "n", "Hit rate", "Always-up", "Edge", "Mean conf.", "Flag"], rows),
              "### By confidence band", "",
              markdown_table(["Window", "Band", "n", "Mean conf.", "Hit rate", "Gap", "Flag"],
                    [[win_names[w], b, s["n"], fpct(s.get("mean_confidence")), fpct(s.get("hit_rate")),
                      scoring.percent(s.get("gap"), sign=True), flag(s["n"], rv)]
                     for w, per in d["bands"].items() for b, s in per.items()])]

    sc_rows = [[win_names[w], h, s["n"], fnum(s.get("brier")), fnum(s.get("log_loss")), fnum(s.get("brier_skill")),
                flag(s["n"], rv)] for w, per in d["scores"].items() for h, s in per["calls"].items()]
    rel_rows = [[r["bin"], r["n"], fpct(r["mean_conf"]), fpct(r["hit_rate"]),
                 f"{fpct(r['wilson_lo'])} to {fpct(r['wilson_hi'])}" if r["n"] else "–"]
                for r in d["scores"]["all"]["reliability"]]
    rq_rows = [[win_names[w], h, s["n"], fpct(s.get("cover50")), fpct(s.get("cover80")), fnum(s.get("is50_pct")),
                fnum(s.get("is80_pct")), fnum(s.get("qs_pct")), flag(s["n"], rv)]
               for w, per in d["scores"].items() for h, s in per["ranges"].items()]
    lines += ["## Proper scores", "",
              "Calls: Brier score (a coin flip scores 0.250) and log loss (coin flip 0.693), lower is better; skill = "
              "1 - Brier / 0.25 (above 0 beats a coin flip).", "",
              markdown_table(["Window", "H", "n", "Brier", "Log loss", "Skill", "Flag"], sc_rows),
              "### Reliability (since start): stated confidence vs hit rate", "",
              markdown_table(["Confidence", "n", "Mean stated", "Hit rate", "Wilson 95%"], rel_rows),
              "### Ranges: interval and quantile scores", "",
              "In % of price, lower is better. Quantile score = mean pinball loss over the four published quantiles "
              "(q10, q25, q75, q90), a coarse CRPS estimate.", "",
              markdown_table(["Window", "H", "n", "50% cover", "80% cover", "50% score", "80% score",
              "Quantile score", "Flag"],
                    rq_rows)]
    a = d["aci"]
    st = a["settings"]
    lines += ["## Adaptive conformal inference (ACI)", "",
              f"Switched **{'on' if st.get('enabled') else 'off'}** (`aci.enabled` in config/ranges.yaml: "
              f"{fval(st.get('enabled'))}); gamma {st['gamma']}, max shift {st['max_shift']}, min history "
              f"{st['min_history']} scored target dates, {'one alpha per regime' if st['by_regime'] else 'one alpha'}. "
              "Current alpha from live outcomes scored by the week's end (the target miss rate is 0.50 for the 50% "
              "band, 0.20 for the 80% band; below target = wider band).", "",
              markdown_table(["H", "Band", "Key", "Steps", "Alpha", "Used (after min history)", "Implied coverage"],
                    [[f"{s['horizon_days']}d", f"{s['band']}%", s["key"], s["steps"], fnum(s["alpha"], 3),
                      fnum(s["effective_alpha"], 3), fpct(s["implied_coverage"], 1)] for s in a["state"]])]
    rep = a.get("replay")

    def cmp_rows(cmp):
        return [[f"{h}d", g, v["before"].get("n"),
                 f"{fpct(v['before'].get('cover50'), 1)} → {fpct(v['after'].get('cover50'), 1)}",
                 f"{fpct(v['before'].get('cover80'), 1)} → {fpct(v['after'].get('cover80'), 1)}",
                 f"{fnum(v['before'].get('score50'))} → {fnum(v['after'].get('score50'))}",
                 f"{fnum(v['before'].get('score80'))} → {fnum(v['after'].get('score80'))}"]
                for h, groups in cmp.items() for g, v in groups.items() if v["before"].get("n")]
    cmp_hdr = ["H", "Group", "n", "50% cover", "80% cover", "50% score", "80% score"]
    if rep and rep.get("note"):
        lines += [f"> {rep['note']}.", ""]
    if rep and rep.get("comparison"):
        lines += [f"Historical replay `{rep['id']}` (`replay.py --aci`), fixed bands → ACI on the same rows. "
                  "**In-sample: the ACI settings in config/ranges.yaml were tuned on this replay window**, so these "
                  "gains are optimistic:", "", markdown_table(cmp_hdr, cmp_rows(rep["comparison"]))]
        ho = rep.get("held_out")
        if ho:
            sel = ho["selected"]
            lines += [f"Held-out check: gamma and the alpha scope (one, or one per regime) picked on as-of dates up to "
                      f"{ho['tune_end']} only (selected gamma {sel['gamma']}, "
                      f"{'per regime' if sel['by_regime'] else 'one alpha'}; "
                      f"{'the config settings' if ho['selected_is_config'] else 'NOT the config settings'}). "
                      "Out of sample, fixed bands → the selected settings on the later as-of dates:", "",
                      markdown_table(cmp_hdr, cmp_rows(ho["test_selected"]))]
            if not ho["selected_is_config"] and ho.get("test_config"):
                lines += ["The config settings on the same later dates (not out of sample: they were chosen on the "
                          "whole window):", "", markdown_table(cmp_hdr, cmp_rows(ho["test_config"]))]
        else:
            lines += ["_No held-out check stored (`replay.py --aci --aci-tune-end DATE`): any ACI proposal is "
                      "provisional._", ""]
    elif not rep:
        lines += ["_No `replay.py --aci` record stored yet: no ACI proposal._", ""]

    lines += [f"## Calibration (latest as of {rec['week_end']})", "",
              markdown_table(["H", "Source", "History n", "Live n", "q10", "q25", "q75", "q90"],
                    [[f"{c['horizon_days']}d", c["source"], c["n_history"], c["n_live"],
                      *(fnum(c[k], 2) for k in ("q10", "q25", "q75", "q90"))] for c in d["calibration"]])]

    ab_hdr = ["Variant", "n", f"50% cover ({hz})", f"80% cover ({hz})", f"80% width ({hz})", f"80% score ({hz})",
              "Score vs current", "Verdict"]
    live = d["live_ablation"]
    lines += ["## Ablation: replay of live scored ranges (since start)", "",
              "Each stored range is rebuilt with one input changed (same quantiles, base and outcome). Inputs that "
              "only exist live (cues, AI calls, earnings and event flags) can only be judged here.", ""]
    if live["n"]:
        lines += [f"Round-trip consistency check against the current config: the replay rebuilds {live['reproduced']} "
                  f"of {live['n']} published ranges exactly (the rest used settings or inputs it holds fixed). This "
                  "checks the decomposition only; it is not an independent validation of the quantile model.", "",
                  markdown_table(ab_hdr, ablation_rows(live))]
    else:
        lines += ["_No scored live ranges yet._", ""]
    hist = d["history_ablation"]
    lines += ["## Ablation: walk-forward on stored prices", ""]
    if hist.get("n"):
        share = ", ".join(f"{k} {scoring.percent(v)}" for k, v in hist["regime_share"].items() if v)
        lines += [f"Last {hist['sessions']} sessions up to {rec['week_end']}, built as `backtest.py` does (each day sees "
                  "only outcomes known before it), plus regime and market-event widening rebuilt from stored bars "
                  f"(regime mix: {share}). No AI, cue or earnings inputs.", "",
                  markdown_table(ab_hdr, ablation_rows(hist))]
    else:
        lines += [f"_Not run: {hist.get('error', 'skipped')}._", ""]

    props = d["proposals"]
    lines += ["## Proposed changes to config/ranges.yaml", "",
              "**Not applied.** Shown for a human to decide in the weekly run; edit `config/ranges.yaml` by hand "
              "and note the change in the commit message.", ""]
    rows = []
    for p in props:
        for ch in p["changes"]:
            rows.append([f"`{ch['param']}`", fval(ch["current"]), fval(ch["proposed"]), p["source"], p["n"], f"{p['rel_score']:+.1%}",
                         " / ".join(f"{fpct(p['cover80_before'].get(h))} → {fpct(p['cover80_after'].get(h))}"
                                    for h in p["cover80_after"]), p["variant"]])
    lines += [markdown_table(["Parameter", "Current", "Proposed", "Evidence", "n", "Score change",
    f"80% cover ({hz})", "Variant"], rows)
              if rows else f"_None: no variant cleared the thresholds (n >= {rv['min_n_recommend']}, score "
              f"{scoring.percent(rv['min_improvement'])} better without coverage falling more than {scoring.percent(rv['coverage_tolerance'])} "
              f"further below target, or 80% coverage "
              f"{scoring.percent(rv['min_coverage_gain'])} closer to target)._\n"]
    drops = [p["variant"] for p in props if p["drop"]]
    lines += ["### What to drop", "", ("- " + "\n- ".join(drops)) if drops else "_Nothing: no input's removal "
              "cleared the thresholds._", "", "### Forecaster confidence", "",
              ("- " + "\n- ".join(d["advice"])) if d["advice"] else
              f"_No advice: no confidence band with n >= {rv['min_n_calls']} misses its stated confidence._", ""]
    lines += ["## Method", "",
              f"- Thresholds from `config/review.yaml`: flag below n={rv['min_n']}, no proposal below "
              f"n={rv['min_n_recommend']} ranges or n={rv['min_n_calls']} calls per band.",
              "- Score change = average over horizons of the relative change in the 80% interval score "
              "(negative is better).",
              "- Each variant changes one input against the current config; proposals are not tested together, "
              "so change one parameter at a time and let the next review confirm it.",
              "- Only coverage falling below target blocks a proposal; over-coverage is priced by the interval "
              "score and narrowed by the daily self-calibration (`calibrate.py`).",
              "- `warmup_bars` and `min_pool` are ablated on price history only. `min_pool` matters only when a "
              "day's pool is smaller than it (live then falls back to normal quantiles, the walk-forward skips the "
              "day), so on two years of bars it rarely binds.",
              "- AI judgement is never backtested: AI drift and AI widening are judged only on live ranges.", ""]
    return "\n".join(lines)
