#!/usr/bin/env python3
"""Build the daily report skeleton and the Slack draft for one market.

Every number and table is written here from stored data; the agent only fills the
`<!-- AGENT:... -->` markers with narrative (and must not change numbers). Writes
reports/<market>/<session_date>.md and work/slack_<market>.md, and prints their paths.
Run after charts.py."""
from __future__ import annotations

import json
import math
import sys
from datetime import timedelta

import pandas as pd
import yaml

import events as ev
from charts import CURRENCY, fmt_call, safe
from common import CONFIG, ROOT, connect, market_arg, require_market, utc_today, vol_index_key

DISCLAIMER = "_Research log, not investment advice. Generated by a scheduled Claude Code routine._"


def money(cur: str, v) -> str:
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "–"
    return f"{CURRENCY.get(cur, '')}{v:,.2f}"


def pct(v, digits=1) -> str:
    return "–" if v is None or pd.isna(v) else f"{v * 100:+.{digits}f}%"


def mark(v) -> str:
    return "–" if v is None or pd.isna(v) else ("✅" if bool(v) else "❌")


def table(header: list[str], rows: list[list]) -> str:
    if not rows:
        return "_none_\n"
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def weekly_review(con, session) -> dict | None:
    """Stored review (review.py) of the ISO week before the session's week, if any."""
    y, w, _ = (session - timedelta(days=7)).isocalendar()
    r = con.execute("SELECT week, report, n_proposals, low_sample, CAST(computed_at AS DATE) AS day "
                    "FROM review_latest WHERE id = ?", [f"{y}-W{w:02d}"]).df()
    if r.empty:
        return None
    out = r.iloc[0].to_dict()
    out["fresh"] = pd.Timestamp(out["day"]).date() == utc_today()  # written in this run -> one Slack line
    return out


def review_line(rv: dict, link: str) -> str:
    n = int(rv["n_proposals"])
    return (f"Weekly review {rv['week']}: {n} proposed range change{'s' if n != 1 else ''} for a human to decide"
            f"{' (low sample)' if rv['low_sample'] else ''} · {link}")


def gather(cfg: dict, con) -> dict:
    q = lambda sql, p=None: con.execute(sql, p or []).df()  # noqa: E731
    ranges = q("SELECT * FROM ranges_latest WHERE as_of_date = (SELECT max(as_of_date) FROM ranges_latest)")
    if ranges.empty:
        raise SystemExit("no published ranges; run ranges.py first")
    as_of = pd.Timestamp(ranges["as_of_date"].iloc[0]).date()
    last_target = con.execute("SELECT max(target_date) FROM range_record").fetchone()[0]
    return {
        "as_of": as_of, "session": pd.Timestamp(ranges["session_date"].iloc[0]).date(), "ranges": ranges,
        "regime": q("SELECT * FROM regime_latest ORDER BY as_of_date DESC LIMIT 1"),
        "features": q("SELECT * FROM features_latest WHERE as_of_date = ?", [as_of]),
        "quotes": q("SELECT * FROM quotes_latest WHERE day = (SELECT max(day) FROM quotes_latest)"),
        "scored": q("SELECT * FROM range_record WHERE target_date = ? ORDER BY ticker, horizon_days", [last_target]),
        "last_target": last_target,
        "calls_scored": q("SELECT * FROM track_record WHERE target_date = (SELECT max(target_date) FROM track_record)"),
        "scorecard": q("""SELECT horizon_days AS h, count(*) AS n, avg(hit50::INT) AS c50, avg(hit80::INT) AS c80,
                                 avg(naive_hit80::INT) AS nc80, avg(width80_pct) AS w, avg(naive_width80_pct) AS nw,
                                 avg(is80_pct) AS s, avg(naive_is80_pct) AS ns
                          FROM range_record GROUP BY h ORDER BY h"""),
        "scorecard_30": q("""SELECT horizon_days AS h, count(*) AS n, avg(hit80::INT) AS c80, avg(naive_hit80::INT) AS nc80
                             FROM range_record WHERE target_date >= current_date - 30 GROUP BY h ORDER BY h"""),
        "direction": q("""SELECT horizon_days AS h, count(*) AS n, avg(hit::INT) AS hit,
                                 avg((actual_return > 0)::INT) AS up FROM track_record GROUP BY h ORDER BY h"""),
        "calibration": q("SELECT * FROM calibration_latest ORDER BY horizon_days"),
        "company_events": q("SELECT date, name FROM company_events WHERE date BETWEEN ? AND ? ORDER BY date",
                            [as_of, as_of + timedelta(days=21)]),
        "review": weekly_review(con, pd.Timestamp(ranges["session_date"].iloc[0]).date()),
    }


def build(cfg: dict, d: dict, settings: dict) -> tuple[str, str, str]:
    cur, market, session = cfg.get("currency", ""), cfg["market"], d["session"]
    charts = f"charts/{session}"
    reg = d["regime"].iloc[0] if not d["regime"].empty else None
    vol_name = cfg["symbols"].get(vol_index_key(cfg) or "", {}).get("name", "vol index")
    regime_line = "Regime: unknown"
    if reg is not None:
        parts = [f"**Regime: {reg['regime']}**" + (" · STRESS" if reg["stress"] else "")]
        if reg["vol_level"] is not None and not pd.isna(reg["vol_level"]):
            parts.append(f"{vol_name} {reg['vol_level']:.2f} ({pct(reg['vol_change_1d'])})")
        parts.append(f"benchmark 5d {pct(reg['bench_ret_5d'])}")
        if reg["bench_vol_10d"] is not None and not pd.isna(reg["bench_vol_10d"]):
            parts.append(f"benchmark 10d vol {reg['bench_vol_10d'] * 100:.1f}%")
        if reg["major_event"]:
            parts.append(f"major events: {', '.join(reg['major_event_names'])}")
        regime_line = " · ".join(parts)
    r = d["ranges"]
    by = {(row.ticker, int(row.horizon_days)): row for row in r.itertuples()}
    feats = d["features"].set_index("ticker") if not d["features"].empty else pd.DataFrame()

    # yesterday: ranges scored on the latest target date
    sc = d["scored"]
    s1 = sc[sc["horizon_days"] == 1] if not sc.empty else sc
    n1 = len(s1)
    h80, h50 = (int(s1["hit80"].sum()), int(s1["hit50"].sum())) if n1 else (0, 0)
    nh80 = int(s1["naive_hit80"].fillna(False).sum()) if n1 else 0
    scored_rows = [[x.ticker, f"{money(cur, x.lo80)}–{money(cur, x.hi80)}",
                    f"{money(cur, x.lo50)}–{money(cur, x.hi50)}", money(cur, x.actual_close),
                    mark(x.hit80), mark(x.hit50), mark(x.naive_hit80)] for x in s1.itertuples()]
    s5 = sc[sc["horizon_days"] == 5] if not sc.empty else sc
    line5 = (f"5-day ranges that matured on the same date: 80% hit {int(s5['hit80'].sum())}/{len(s5)}, "
             f"50% hit {int(s5['hit50'].sum())}/{len(s5)}." if len(s5) else "")
    cs = d["calls_scored"]
    calls_hit = int(cs["hit"].sum()) if not cs.empty else 0
    call_rows = [[x.ticker, f"{x.horizon_days}d", x.direction, f"{x.confidence:.0%}", pct(x.actual_return, 2), mark(x.hit)]
                 for x in cs.itertuples()]

    # today: ranges by sector
    today_rows = []
    for sector, members in (cfg.get("sectors") or {"": list(cfg["tickers"])}).items():
        for t in members:
            a, b = by.get((t, 1)), by.get((t, 5))
            if a is None and b is None:
                q = feats.loc[t]["quality"] if t in feats.index else "no data"
                today_rows.append([t, sector, "–", "–", "–", "–", f"no range ({q})", "", ""])
                continue
            base = (a or b).base_close
            call = next((fmt_call(x.direction, x.confidence) for x in (a, b) if x is not None and x.direction), "no call")
            notes = "; ".join(sorted({n for x in (a, b) if x is not None for n in (list(x.notes) if x.notes is not None else [])}))
            today_rows.append([
                t, sector, money(cur, base),
                f"{money(cur, a.lo80)}–{money(cur, a.hi80)}" if a else "–",
                f"{money(cur, a.lo50)}–{money(cur, a.hi50)}" if a else "–",
                f"{money(cur, b.lo80)}–{money(cur, b.hi80)}" if b else "–",
                call, pct(feats.loc[t]["cue_change_pct"], 2) if t in feats.index else "–", notes])

    cue_rows = [[x.symbol, cfg["symbols"].get(x.symbol, {}).get("name", x.symbol), f"{x.price:,.2f}", pct(x.change_pct, 2)]
                for x in d["quotes"].itertuples() if x.symbol in cfg["symbols"]]
    adr_rows = [[x.symbol.replace(":ADR", ""), cfg["tickers"].get(x.symbol.replace(":ADR", ""), {}).get("adr", ""),
                 f"{x.price:,.2f}", pct(x.change_pct, 2)] for x in d["quotes"].itertuples() if x.symbol.endswith(":ADR")]

    upcoming = [(e["date"], e["name"], "major" if e["major"] else "")
                for e in ev.market_events(cfg, d["as_of"] + timedelta(days=1), d["as_of"] + timedelta(days=21))]
    upcoming += [(pd.Timestamp(x.date).date(), x.name, "company") for x in d["company_events"].itertuples()]
    upcoming.sort()

    sc_rows = [[f"{x.h}d", x.n, f"{x.c50:.0%}", f"{x.c80:.0%}", f"{x.nc80:.0%}" if not pd.isna(x.nc80) else "–",
                f"{x.w:.2f}", f"{x.nw:.2f}" if not pd.isna(x.nw) else "–", f"{x.s:.3f}",
                f"{x.ns:.3f}" if not pd.isna(x.ns) else "–"] for x in d["scorecard"].itertuples()]
    dir_rows = [[f"{x.h}d", x.n, f"{x.hit:.0%}", f"{x.up:.0%}"] for x in d["direction"].itertuples()]
    cal_rows = [[f"{x.horizon_days}d", x.source, x.n_history, x.n_live, f"{x.q10:.2f} / {x.q90:.2f}"]
                for x in d["calibration"].itertuples()]
    partial = sorted(feats.index[feats["quality"] == "PARTIAL"]) if len(feats) else []
    blocked = sorted(feats.index[feats["quality"] == "BLOCKED"]) if len(feats) else []

    md = [f"# Market brief: {cfg['name']}, {session}", "", DISCLAIMER, "",
          "## Headline", "<!-- AGENT:headline -->", "",
          "## Yesterday", "<!-- AGENT:yesterday -->", "",
          f"### Ranges scored (target date {d['last_target'] or '–'})", "",
          (f"Next-day ranges: **80% hit {h80}/{n1}** (naive {nh80}/{n1}) · 50% hit {h50}/{n1}" if n1 else
           "No ranges have matured yet."), "",
          table(["Ticker", "80% range", "50% range", "Actual", "80%", "50%", "Naive 80%"], scored_rows),
          line5, "",
          "### Calls scored", "", table(["Ticker", "H", "Call", "Conf.", "Move", "Hit"], call_rows),
          f"## Today ({session})", "", regime_line, "",
          f"![Overview]({charts}/overview.png)", "",
          table(["Ticker", "Sector", "Close", "Next day 80%", "Next day 50%", "5 days 80%", "Call", "Cue", "Notes"], today_rows),
          "<!-- AGENT:calls -->", "",
          "### Overnight cues and global factors", "", table(["Symbol", "Name", "Last", "Change"], cue_rows),
          *(["### ADRs (US-listed shares, previous US session)", "", table(["Ticker", "ADR", "Last", "Change"], adr_rows)]
            if adr_rows else []),
          "## Tomorrow and this week", "",
          table(["Date", "Event", "Type"], [[str(a), b, c] for a, b, c in upcoming]),
          "<!-- AGENT:outlook -->", "",
          "## By sector", ""]
    for sector, members in (cfg.get("sectors") or {}).items():
        md += [f"### {sector}", ""]
        md += [f"![{t}]({charts}/{safe(t)}.png)" for t in members if (t, 1) in by or (t, 5) in by]
        md += ["", f"<!-- AGENT:sector:{sector} -->", ""]
    md += ["## Track record", "",
           "Ranges (targets 50% / 80%; width and score in % of price, score lower is better):", "",
           table(["H", "n", "50% cover", "80% cover", "Naive 80%", "Width", "Naive width", "Score", "Naive score"], sc_rows),
           "Up/down calls vs the always-up baseline:", "", table(["H", "n", "Hit rate", "Always-up"], dir_rows),
           *([review_line(d["review"], d["review"]["report"].rsplit("/", 1)[-1]), ""] if d.get("review") else []),
           "## Data quality", "",
           f"- Indicators: {len(feats) - len(partial) - len(blocked)} OK, partial: {', '.join(partial) or 'none'}, "
           f"blocked: {', '.join(blocked) or 'none'}",
           f"- Regime notes: {'; '.join(reg['notes']) if reg is not None and reg['notes'] is not None and len(reg['notes']) else 'none'}", "",
           table(["H", "Calibration", "History n", "Live n", "q10 / q90"], cal_rows),
           "<!-- AGENT:data_quality -->", ""]
    report = "\n".join(md)

    url = f"{settings['repo_url']}/blob/{settings['branch']}/reports/{market}/{session}.md"
    calls = [(t, x) for (t, h), x in sorted(by.items()) if x.direction in ("up", "down")]
    head = f"*Market brief · {cfg['name']} · {session}*"
    if reg is not None:
        head += f" · {reg['regime']}"
        if reg["vol_level"] is not None and not pd.isna(reg["vol_level"]):
            head += f" ({vol_name} {reg['vol_level']:.1f})"
    slack = [head,
             "<!-- AGENT:headline (one line) -->",
             (f"Yesterday: next-day 80% ranges hit {h80}/{n1} (naive {nh80}/{n1}) · 50% hit {h50}/{n1}"
              + (f" · calls {calls_hit}/{len(cs)}" if len(cs) else "")) if n1 else "Yesterday: no ranges matured yet.",
             "Today's calls (80% range for the call's horizon):" if calls else
             f"No calls today; ranges for all {len(cfg['tickers'])} stocks are in the report."]
    slack += [f"• {t} {fmt_call(x.direction, x.confidence)} ({'next day' if x.horizon_days == 1 else f'{x.horizon_days} days'})"
              f" · {money(cur, x.lo80)}–{money(cur, x.hi80)}" for t, x in calls[:6]]
    if len(calls) > 6:
        slack.append(f"• +{len(calls) - 6} more in the report")
    slack += ["News: <!-- AGENT:news (the 2 most material items, one line each) -->",
              "<!-- AGENT:failures (only if a collector failed; otherwise delete this line) -->",
              f"Report and charts: {url}"]
    if d.get("review") and d["review"]["fresh"]:  # weekly review written in this run: one line
        slack.insert(-1, review_line(d["review"], f"{settings['repo_url']}/blob/{settings['branch']}/{d['review']['report']}"))
    return report, "\n".join(slack) + "\n", url


def main() -> int:
    cfg = require_market(market_arg(__doc__).parse_args())
    settings = yaml.safe_load((CONFIG / "settings.yaml").read_text())
    d = gather(cfg, connect(cfg["market"]))
    report, slack, url = build(cfg, d, settings)
    rpath = ROOT / "reports" / cfg["market"] / f"{d['session']}.md"
    rpath.parent.mkdir(parents=True, exist_ok=True)
    rpath.write_text(report)
    spath = ROOT / "work" / f"slack_{cfg['market']}.md"
    spath.parent.mkdir(parents=True, exist_ok=True)
    spath.write_text(slack)
    print(json.dumps({"step": "report", "market": cfg["market"], "report": str(rpath.relative_to(ROOT)),
                      "slack_draft": str(spath.relative_to(ROOT)), "url": url,
                      "agent_markers": report.count("<!-- AGENT:")}, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
