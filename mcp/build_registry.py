"""Writes web/lib/tools/registry.generated.ts from mcp/tools.yaml and mcp/agents/*.yaml (session B5).

The web tier cannot read files outside web/ on Vercel, so the tool definitions it enforces are generated here and
checked in; tests/test_b5_tools.py fails when the generated file is stale. Run from the repo root:
    python mcp/build_registry.py           # write
    python mcp/build_registry.py --check   # exit 1 when stale
Every agent's tools must exist and be allowed in each of its channels (a tools.yaml channel value of false)."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
TOOLS_YAML = REPO / "mcp" / "tools.yaml"
AGENTS_DIR = REPO / "mcp" / "agents"
OUTPUT = REPO / "web" / "lib" / "tools" / "registry.generated.ts"
AGENT_KEYS = {"agent", "channels", "enabled", "tools", "daily_write_budget", "daily_read_budget", "fail_to"}
HEADER = ("// GENERATED by mcp/build_registry.py from mcp/tools.yaml and mcp/agents/*.yaml. Do not edit;\n"
          "// change the sources and run `python mcp/build_registry.py` "
          "(tests/test_b5_tools.py checks it is current).\n")


def resolve_inputs(inputs: dict, common: dict) -> dict:
    """Each input with its `$ref: common_inputs.<name>` merged under its own keys (own keys win)."""
    resolved = {}
    for name, spec in (inputs or {}).items():
        spec = dict(spec)
        ref = spec.pop("$ref", None)
        if ref:
            base = dict(common[ref.removeprefix("common_inputs.")])
            base.update(spec)
            spec = base
        resolved[name] = spec
    return resolved


def load_tools() -> dict:
    doc = yaml.safe_load(TOOLS_YAML.read_text(encoding="utf-8"))
    common = doc["common_inputs"]
    tools = []
    for tool in doc["tools"]:
        tool = dict(tool)
        tool["inputs"] = resolve_inputs(tool.get("inputs"), common)
        tools.append(tool)
    return {"version": doc["version"], "channels": doc["channels"], "refusal_codes": doc["refusal_codes"],
            "tools": tools}


def load_agents(tools: list[dict], channels: list[str]) -> list[dict]:
    by_name = {tool["name"]: tool for tool in tools}
    agents = []
    for path in sorted(AGENTS_DIR.glob("*.yaml")):
        agent = yaml.safe_load(path.read_text(encoding="utf-8"))
        problems = agent_problems(agent, path.stem, by_name, channels)
        if problems:
            raise SystemExit(f"{path.name}: " + "; ".join(problems))
        agents.append(agent)
    return agents


def agent_problems(agent: dict, stem: str, by_name: dict, channels: list[str]) -> list[str]:
    problems = []
    if set(agent) != AGENT_KEYS:
        problems.append(f"keys must be {sorted(AGENT_KEYS)}")
        return problems
    if agent["agent"] != stem:
        problems.append("agent must equal the file name")
    if not isinstance(agent["enabled"], bool):
        problems.append("enabled must be true or false")
    for key in ("daily_write_budget", "daily_read_budget"):
        if not isinstance(agent[key], int) or isinstance(agent[key], bool) or agent[key] < 0:
            problems.append(f"{key} must be a whole number >= 0")
    for channel in agent["channels"]:
        if channel not in channels:
            problems.append(f"unknown channel {channel}")
            continue
        for name in agent["tools"]:
            tool = by_name.get(name)
            if tool is None:
                problems.append(f"unknown tool {name}")
            elif tool["channels"].get(channel) is False:
                problems.append(f"{name} is not allowed in channel {channel}")
    writes = [name for name in agent["tools"] if by_name.get(name, {}).get("kind") == "write"]
    if writes and agent["daily_write_budget"] == 0:
        problems.append("write tools need a daily_write_budget above 0")
    return problems


def render() -> str:
    registry = load_tools()
    agents = load_agents(registry["tools"], registry["channels"])
    parts = [
        HEADER,
        f"export const TOOLS_VERSION = {json.dumps(registry['version'])} as const;\n",
        f"export const CHANNELS = {json.dumps(registry['channels'])} as const;\n",
        f"export const REFUSAL_CODES = {json.dumps(registry['refusal_codes'])} as const;\n",
        "export const TOOL_DEFINITIONS: readonly unknown[] = "
        f"{json.dumps(registry['tools'], indent=2, ensure_ascii=False)};\n",
        f"export const AGENT_DEFINITIONS: readonly unknown[] = {json.dumps(agents, indent=2, ensure_ascii=False)};\n",
    ]
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the generated file is stale")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(REPO)} is stale: run python mcp/build_registry.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
